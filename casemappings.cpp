   // Initializes sets of mappings for case folding.  The mappings are used by 
   // the code in fastutf8.cpp for case-insensitive content matching.
   //
   void CaseMappingSetupUtf8(void)
   {
      unsigned int i, j, iMax, jMax;
   
      // Set up mappings for two-byte code points.
      i = j = 0;
      iMax = CM00nDataLen;
   
      while (i < iMax)
      {
         if (0xC000 + i == CM00nSetup[j][0])
         {
            CM00n[i] = CM00nSetup[j][1];
            ++j;
         }
         else
         {
            CM00n[i] = 0xC000 + (0xFFFF & i);
         }
   
         ++i;
      }
   
      // Set up mappings for three-byte code points.  They fall in the 
      // 0x00Ennnnn range.  First set up the whole range with non-folded / 
      // like-for-like three-byte mappings, then go back though the portions of 
      // the range defined in the CME*Setup arrays to apply the folded mappings.
      i = 0;
      iMax = CMEnnDataLen;
   
      while (i < iMax)
      {
         CMEnn[i] = 0xE00000 | i;
         ++i;
      }
   
      // Mappings for three-byte Georgian and Cherokee code points.
      i = j = 0;
      jMax = CME18Len;
   
      while (i < iMax && j < jMax)
      {
         if (0xE18000 + i == CME18Setup[j][0])
         {
            CMEnn[0x18000 + i] = CME18Setup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for three-byte Georgian, Cyrillic, Greek, and Latin code 
      // points.
      i = j = 0;
      jMax = CME1BLen;
   
      while (i < iMax && j < jMax)
      {
         if (0xE1B000 + i == CME1BSetup[j][0])
         {
            CMEnn[0x1b000 + i] = CME1BSetup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for three-byte Roman numerals and a few other code points.
      i = j = 0;
      jMax = CME28Len;
   
      while (i < iMax && j < jMax)
      {
         if (0xE28000 + i == CME28Setup[j][0])
         {
            CMEnn[0x28000 + i] = CME28Setup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for circled Latin code points.
      i = j = 0;
      jMax = CME29Len;
   
      while (i < iMax && j < jMax)
      {
         if (0xE29000 + i == CME29Setup[j][0])
         {
            CMEnn[0x29000 + i] = CME29Setup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for three-byte Glagolitic, Latin, and Coptic code points.
      i = j = 0;
      jMax = CME2BLen;
   
      while (i < iMax && j < jMax)
      {
         if (0xE2B000 + i == CME2BSetup[j][0])
         {
            CMEnn[0x2B000 + i] = CME2BSetup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for more three-byte Cyrillic and Latin code points.
      i = j = 0;
      jMax = CMEA9Len;
   
      while (i < iMax && j < jMax)
      {
         if (0xEA9000 + i == CMEA9Setup[j][0])
         {
            CMEnn[0xA9000 + i] = CMEA9Setup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for three-byte Cherokee code points.
      i = j = 0;
      jMax = CMEAALen;
   
      while (i < iMax && j < jMax)
      {
         if (0xEAA000 + i == CMEAASetup[j][0])
         {
            CMEnn[0xAA000 + i] = CMEA9Setup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Mappings for three-byte full width Latin code points.
      i = j = 0;
      jMax = CMEFBLen;
   
      while (i < iMax && j < jMax)
      {
         if (0xEFB000 + i == CMEFBSetup[j][0])
         {
            CMEnn[0xFB000 + i] = CMEFBSetup[j][1];
            ++j;
         }
   
         ++i;
      }
   
      // Set up mappings for four-byte code points.  They fall in the 
      // 0xF09nnnnn range.  First set up the relevant portions of the range 
      // with non-folded / like-for-like four-byte mappings, then apply the 
      // folded mappings based on the CM9*Setup arrays.
      //
      // Mappings for four-byte Deseret and Osage code points.
      i = 0;
      iMax = CM9nnDataLen;
   
      while (i < iMax)
      {
         CM909[i] = 0xF0909000 | i;
         ++i;
      }
   
      i = j = 0;
      jMax = CM909Len;
   
      while (i < iMax && j < jMax)
      {
         if (0xF0909000 + i == CM909Setup[j][0])
         {
            CM909[i] = CM909Setup[j][1];
            ++j;
         }
         else
         {
            CM909[i] = 0xF0909000 + i;
         }
   
         ++i;
      }
   
      // Mappings for four-byte old Hungarian code points.
      i = 0;
   
      while (i < iMax && j < jMax)
      {
         CM90B[i] = 0xF090B000 | i;
         ++i;
      }
   
      i = j = 0;
      jMax = CM90BLen;
   
      while (i < iMax && j < jMax)
      {
         if (0xF090B000 + i == CM90BSetup[j][0])
         {
            CM90B[i] = CM90BSetup[j][1];
            ++j;
         }
         else
         {
            CM90B[i] = 0xF090B000 + i;
         }
   
         ++i;
      }
   
      // Mappings for four-byte Warang code points.
      i = 0;
   
      while (i < iMax && j < jMax)
      {
         CM91A[i] = 0xF091A000 | i;
         ++i;
      }
   
      i = j = 0;
      jMax = CM91ALen;
   
      while (i < iMax && j < jMax)
      {
         if (0xF091A000 + i == CM91ASetup[j][0])
         {
            CM91A[i] = CM91ASetup[j][1];
            ++j;
         }
         else
         {
            CM91A[i] = 0xF091A000 + i;
         }
   
         ++i;
      }
   
      // Mappings for four-byte Medefaidrin code points.
      i = 0;
   
      while (i < iMax && j < jMax)
      {
         CM96B[i] = 0xF096B000 | i;
         ++i;
      }
   
      i = j = 0;
      jMax = CM96BLen;
   
      while (i < iMax && j < jMax)
      {
         if (0xF096B000 + i == CM96BSetup[j][0])
         {
            CM96B[i] = CM96BSetup[j][1];
            ++j;
         }
         else
         {
            CM96B[i] = 0xF096B000 + i;
         }
   
         ++i;
      }
   
      // Mappings for four-byte Adlam code points.
      i = 0;
   
      while (i < iMax && j < jMax)
      {
         CM9EA[i] = 0xF09EA000 | i;
         ++i;
      }
   
      i = j = 0;
      jMax = CM9EALen;
   
      while (i < iMax && j < jMax)
      {
         if (0xF09EA000 + i == CM9EASetup[j][0])
         {
            CM9EA[i] = CM9EASetup[j][1];
            ++j;
         }
         else
         {
            CM9EA[i] = 0xF09EA000 + i;
         }
   
         ++i;
      }
   
      return;
   }
